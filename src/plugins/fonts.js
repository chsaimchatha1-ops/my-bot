function transformText(fontNum, str) {
    if (fontNum >= 35 && fontNum <= 50) {
        // Aesthetic Frames
        const frames = {
            35: `✨ ${str} ✨`,
            36: `🌸 ${str} 🌸`,
            37: `💎 ${str} 💎`,
            38: `🛡️ [ ${str} ] 🛡️`,
            39: `❤️ ${str} ❤️`,
            40: `🎀 ${str} 🎀`,
            41: `🔥 ${str} 🔥`,
            42: `👑 ── ${str} ── 👑`,
            43: `⚡ ${str} ⚡`,
            44: `🎵 ── ${str} ── 🎵`,
            50: `╔══════════════╗\n  ${str}\n╚══════════════╝`
        };
        return frames[fontNum] || `✨ ${str} ✨`;
    }

    if (fontNum === 25) {
        // Strikethrough
        return str.split('').join('\u0336') + '\u0336';
    }

    const map = FONT_MAPS[fontNum] || FONT_MAPS[1];
    return str.split('').map(char => map[char] || char).join('');
}

module.exports = {
    name: 'fonts',

    async handle(sock, msg, cmd, args, from) {
        if (/^font([1-9]|[1-4][0-9]|50)$/.test(cmd)) {
            const fontNum = parseInt(cmd.replace('font', ''), 10);
            const textToConvert = args.join(' ');

            if (!textToConvert) {
                return sock.sendMessage(from, {
                    text: `❌ *Usage:* \`.${cmd} Your text here\`\n💡 Converts text into font design #${fontNum}`
                }, { quoted: msg });
            }

            const converted = transformText(fontNum, textToConvert);
            await sock.sendMessage(from, { text: converted }, { quoted: msg });
            return true;
        }
        return false;
    }
};
